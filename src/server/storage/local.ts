import "server-only";

import os from "node:os";
import path from "node:path";
import { mkdir, readFile, rm, writeFile } from "node:fs/promises";

import type { DocumentExtension } from "@/server/documents/file-types";

/**
 * Local disk implementation of document storage.
 *
 * The rest of the app only sees keys, never absolute paths. Phase 10 can swap
 * this module for S3/R2 without touching services: the contract is
 * "save bytes under a key, read them back, delete them".
 *
 * `UPLOAD_DIR` overrides the location. Without it, serverless platforms get the
 * only writable directory they have (`/tmp`), so the demo uploads work for the
 * lifetime of the function instance. Files there are ephemeral: a retry after
 * a cold start will not find the original bytes.
 */
const ROOT = path.resolve(
  /* turbopackIgnore: true */ process.env.UPLOAD_DIR ??
    (process.env.VERCEL ? path.join(os.tmpdir(), "recall-uploads") : "uploads"),
);

/**
 * Resolves a key inside the storage root and refuses anything that escapes it.
 * Keys are generated by us, but this is the check that makes a future caller
 * with user input safe by construction.
 */
function resolveKey(key: string): string {
  const resolved = path.resolve(ROOT, key);
  if (resolved !== ROOT && !resolved.startsWith(ROOT + path.sep)) {
    throw new Error("Invalid storage key.");
  }
  return resolved;
}

export function storageKeyFor(
  organizationId: string,
  documentId: string,
  extension: DocumentExtension,
): string {
  return `${organizationId}/${documentId}.${extension}`;
}

/**
 * Fixes a Turbopack build warning: these paths are only known at runtime, so
 * tracing them would make the builder walk the whole project. The comment
 * tells the bundler to ignore the call; runtime behaviour is unchanged.
 */
export async function saveFile(key: string, data: Buffer): Promise<void> {
  const filePath = resolveKey(key);
  await mkdir(path.dirname(/* turbopackIgnore: true */ filePath), {
    recursive: true,
  });
  await writeFile(/* turbopackIgnore: true */ filePath, data);
}

export async function readStoredFile(key: string): Promise<Buffer> {
  return readFile(/* turbopackIgnore: true */ resolveKey(key));
}

/** Missing files are not an error: deleting is meant to be idempotent. */
export async function deleteStoredFile(key: string): Promise<void> {
  await rm(/* turbopackIgnore: true */ resolveKey(key), { force: true });
}
